// DEVELOPMENT ONLY: promote an existing test user to Admin.
if (app.Environment.IsDevelopment())
{
    var adminEmail = builder.Configuration["DevelopmentAdminEmail"];

    if (!string.IsNullOrWhiteSpace(adminEmail))
    {
        using var scope = app.Services.CreateScope();
        var db = scope.ServiceProvider.GetRequiredService<AppDb>();

        var user = db.Users.FirstOrDefault(
            u => u.Email == adminEmail.Trim().ToLowerInvariant());

        if (user != null && user.Role != "Admin")
        {
            user.Role = "Admin";
            db.SaveChanges();
        }
    }
}
app.MapControllerRoute(name:"default",pattern:"{controller=Home}/{action=Index}/{id?}");app.Run();

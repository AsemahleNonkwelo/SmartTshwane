using Microsoft.AspNetCore.Authentication.Cookies;
using Microsoft.EntityFrameworkCore;
using SmartTshwane.Data;
using SmartTshwane.Models;
var builder = WebApplication.CreateBuilder(args);
builder.Services.AddControllersWithViews();
builder.Services.AddDbContext<AppDb>(options => {
 if(builder.Configuration.GetValue<bool>("UsePostgres")) options.UseNpgsql(builder.Configuration.GetConnectionString("Default"));
 else options.UseSqlite(builder.Configuration.GetConnectionString("Default"));
});
builder.Services.AddAuthentication(CookieAuthenticationDefaults.AuthenticationScheme).AddCookie(options => {
 options.LoginPath="/Account/Login"; options.AccessDeniedPath="/Account/Denied"; options.Cookie.HttpOnly=true; options.Cookie.SameSite=SameSiteMode.Lax; options.Cookie.SecurePolicy=CookieSecurePolicy.SameAsRequest;
});
builder.Services.AddAuthorization();
var app=builder.Build();
app.UseExceptionHandler("/Home/Error");
app.UseStaticFiles(); app.UseRouting(); app.UseAuthentication(); app.UseAuthorization();
using(var scope=app.Services.CreateScope()) {var db=scope.ServiceProvider.GetRequiredService<AppDb>(); db.Database.EnsureCreated();

 if(db.Database.IsNpgsql()) {
  db.Database.ExecuteSqlRaw("ALTER TABLE \"Users\" ADD COLUMN IF NOT EXISTS \"PhoneNumber\" text NULL");
  db.Database.ExecuteSqlRaw("ALTER TABLE \"Requests\" ADD COLUMN IF NOT EXISTS \"Latitude\" double precision NULL");
  db.Database.ExecuteSqlRaw("ALTER TABLE \"Requests\" ADD COLUMN IF NOT EXISTS \"Longitude\" double precision NULL");
  db.Database.ExecuteSqlRaw("ALTER TABLE \"Categories\" ADD COLUMN IF NOT EXISTS \"DepartmentId\" integer NULL");
  db.Database.ExecuteSqlRaw("CREATE TABLE IF NOT EXISTS \"Departments\" (\"Id\" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, \"Name\" text NOT NULL)");
  db.Database.ExecuteSqlRaw("CREATE TABLE IF NOT EXISTS \"Notifications\" (\"Id\" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, \"UserId\" integer NOT NULL, \"Message\" text NOT NULL, \"IsRead\" boolean NOT NULL DEFAULT false, \"CreatedUtc\" timestamp with time zone NOT NULL)");
 } else {
